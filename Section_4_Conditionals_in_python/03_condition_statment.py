sign = "+"
num1 = 10
num2 = 20

if sign == "+":
    if num1 > num2:
        print(f"{num1} is greater than {num2}")
    else:
        print(f"{num2} is greater than {num1}")
elif sign == "-":
    if num1 > num2:
        print(f"{num1} is greater than {num2}")
    else:
        print(f"{num2} is greater than {num1}")
elif sign == "*":
    if num1 > num2:
        print(f"{num1} is greater than {num2}")
